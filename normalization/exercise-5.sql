-- Q1: Every order with its customer
SELECT
    o.order_id,
    o.order_date,
    c.first_name || ' ' || c.last_name AS customer,
    COUNT(ol.product_id) AS products_in_order
FROM
    sales_order o
    JOIN client c ON c.client_id = o.client_id
    JOIN order_line ol ON ol.order_id = o.order_id
GROUP BY
    o.order_id,
    o.order_date,
    customer
ORDER BY
    o.order_id;

-- Q2: Outstanding invoices (not yet paid)
SELECT
    i.invoice_id,
    o.order_id,
    c.first_name || ' ' || c.last_name AS customer,
    i.invoice_date,
    i.payment_method
FROM
    invoice i
    JOIN sales_order o ON o.order_id = i.order_id
    JOIN client c ON c.client_id = o.client_id
WHERE
    i.payment_date IS NULL;

-- Q3: Revenue by client
SELECT
    c.first_name || ' ' || c.last_name AS customer,
    SUM(il.quantity * p.unit_price) AS total_spent
FROM
    client c
    JOIN sales_order o USING (client_id)
    JOIN invoice i USING (order_id)
    JOIN invoice_line il USING (invoice_id)
    JOIN product p USING (product_id)
GROUP BY
    customer
ORDER BY
    total_spent DESC;