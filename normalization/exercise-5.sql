/* ──────────────────────────────────────────────────
Fresh start
────────────────────────────────────────────────── */
DROP TABLE IF EXISTS invoice_line;

DROP TABLE IF EXISTS invoice;

DROP TABLE IF EXISTS order_line;

DROP TABLE IF EXISTS sales_order;

DROP TABLE IF EXISTS product;

DROP TABLE IF EXISTS client_phone;

DROP TABLE IF EXISTS client;

/* ──────────────────────────────────────────────────
Create tables
────────────────────────────────────────────────── */
CREATE TABLE
    client (
        client_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        first_name VARCHAR(100) NOT NULL,
        last_name VARCHAR(100) NOT NULL,
        fax_number VARCHAR(30),
        email VARCHAR(255) UNIQUE
    );

CREATE TABLE
    client_phone (
        client_id INTEGER NOT NULL REFERENCES client (client_id) ON DELETE CASCADE,
        phone_no VARCHAR(30) NOT NULL,
        PRIMARY KEY (client_id, phone_no)
    );

CREATE TABLE
    product (
        product_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        product_code INTEGER NOT NULL UNIQUE, -- 1, 2, 3… from the sheet
        product_name TEXT NOT NULL,
        unit_price NUMERIC(10, 2) NOT NULL CHECK (unit_price >= 0)
    );

CREATE TABLE
    sales_order (
        order_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        client_id INTEGER NOT NULL REFERENCES client (client_id) ON DELETE RESTRICT,
        order_date DATE NOT NULL
    );

CREATE TABLE
    order_line (
        order_id INTEGER NOT NULL REFERENCES sales_order (order_id) ON DELETE CASCADE,
        product_id INTEGER NOT NULL REFERENCES product (product_id) ON DELETE RESTRICT,
        quantity INTEGER NOT NULL DEFAULT 1 CHECK (quantity > 0),
        PRIMARY KEY (order_id, product_id)
    );

CREATE TABLE
    invoice (
        invoice_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        order_id INTEGER NOT NULL REFERENCES sales_order (order_id) ON DELETE CASCADE,
        invoice_date DATE NOT NULL,
        payment_date DATE,
        payment_method VARCHAR(40)
    );

CREATE TABLE
    invoice_line (
        invoice_id INTEGER NOT NULL REFERENCES invoice (invoice_id) ON DELETE CASCADE,
        product_id INTEGER NOT NULL REFERENCES product (product_id) ON DELETE RESTRICT,
        quantity INTEGER NOT NULL DEFAULT 1 CHECK (quantity > 0),
        PRIMARY KEY (invoice_id, product_id)
    );

